@dataclass(frozen=True)
class FieldDefinition:
    """A single Excel column exposed as a C# configuration field."""

    name: str
    type_name: str
    column_index: int
    tips: str = ""


@dataclass(frozen=True)
class TableDefinition:
    """One non-empty worksheet and its generated client/server models."""

    workbook: Path
    sheet_name: str
    table_id_name: str
    client_class_name: str | None
    server_class_name: str | None
    client_fields: list[FieldDefinition]
    server_fields: list[FieldDefinition]
    values: list[list[Any]]


def normalize_label(value: Any) -> str:
    """Normalize a first-column metadata label for case-insensitive matching."""

    return str(value).strip().upper()


def is_empty(value: Any) -> bool:
    """Return whether an Excel cell should be treated as an unspecified value."""

    return value is None or (isinstance(value, str) and not value.strip())


def get_first_value(sheet: xlrd.sheet.Sheet, labels: set[str]) -> Any:
    """Find the first non-empty cell on a metadata row matched by labels."""

    for row_index in range(sheet.nrows):
        if normalize_label(sheet.cell_value(row_index, 0)) not in labels:
            continue
        for column_index in range(1, sheet.ncols):
            value = sheet.cell_value(row_index, column_index)
            if not is_empty(value):
                return value
        return None
    return None


def get_metadata_row(sheet: xlrd.sheet.Sheet, label: str) -> int:
    """Return a required metadata row index or raise a contextual error."""

    for row_index in range(sheet.nrows):
        if normalize_label(sheet.cell_value(row_index, 0)) == label:
            return row_index
    raise ValueError(f"{sheet.name} 缺少 {label} 行。")


def parse_class_name(value: Any, side: str, sheet: xlrd.sheet.Sheet) -> str | None:
    """Build a prefixed side-specific class name from an OUT metadata value."""

    if is_empty(value) or normalize_label(value) == "NO":
        return None
    base_name = str(value).strip()
    if not IDENTIFIER_PATTERN.fullmatch(base_name):
        raise ValueError(f"{sheet.name} 的 {side} 类名 {base_name!r} 不是合法 C# 标识符。")
    suffix = "Client" if side == "client" else "Server"
    return f"Cfg{base_name[0].upper()}{base_name[1:]}{suffix}"


def parse_table_id_name(sheet: xlrd.sheet.Sheet) -> str:
    """Convert a worksheet name into the matching generated table enum member."""

    if not IDENTIFIER_PATTERN.fullmatch(sheet.name):
        raise ValueError(f"{sheet.name} 不是合法 C# 配置表枚举名称。")
    return f"{sheet.name[0].upper()}{sheet.name[1:]}"


def parse_type(value: Any, sheet: xlrd.sheet.Sheet, column_index: int) -> str:
    """Parse one supported scalar or one-dimensional array C# type."""

    raw_type = str(value).strip().lower()
    is_array = raw_type.endswith("[]")
    scalar_type = raw_type[:-2].strip() if is_array else raw_type
    normalized = SCALAR_TYPES.get(scalar_type)
    if normalized is None:
        raise ValueError(
            f"{sheet.name} 第 {column_index + 1} 列类型 {value!r} 不受支持。"
        )
    return f"{normalized}[]" if is_array else normalized


def is_enabled(value: Any) -> bool:
    """Parse an endpoint field switch from a metadata cell."""

    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return value == 1
    return str(value).strip().lower() in {"yes", "y", "true", "1"}


def parse_fields(
    sheet: xlrd.sheet.Sheet,
    key_row: int,
    type_row: int,
    enabled_row: int,
) -> list[FieldDefinition]:
    """Read the endpoint's enabled field columns and validate their schema."""

    fields: list[FieldDefinition] = []
    tips_row = next((index for index in range(sheet.nrows)
                     if normalize_label(sheet.cell_value(index, 0)) == "TIPS"), None)
    names: set[str] = set()
    for column_index in range(1, sheet.ncols):
        if not is_enabled(sheet.cell_value(enabled_row, column_index)):
            continue
        key = str(sheet.cell_value(key_row, column_index)).strip()
        if not key:
            raise ValueError(f"{sheet.name} 第 {column_index + 1} 列已启用但 KEY 为空。")
        if not IDENTIFIER_PATTERN.fullmatch(key):
            raise ValueError(f"{sheet.name} 第 {column_index + 1} 列 KEY {key!r} 非法。")
        if key in names:
            raise ValueError(f"{sheet.name} 的 KEY {key!r} 重复。")
        names.add(key)
        fields.append(
            FieldDefinition(
                key,
                parse_type(sheet.cell_value(type_row, column_index), sheet, column_index),
                column_index,
                read_field_tips(sheet, tips_row, column_index, key),
            )
        )
    return fields


def read_field_tips(sheet: xlrd.sheet.Sheet, tips_row: int | None, column_index: int, key: str) -> str:
    """保留普通TIPS；xlwt超链接无公式缓存时使用同一格式化描述生成XML注释。"""
    tips = str(sheet.cell_value(tips_row, column_index)).strip() if tips_row is not None else ""
    if tips:
        return tips
    # legacy.xls公式写入后尚未被Excel重算，xlrd读到空缓存；描述必须与可点击提示同源。
    from config_xls_formatting import GAMEPLAY_REFERENCE_LABELS, CHINESE_TIPS
    return GAMEPLAY_REFERENCE_LABELS.get((sheet.name, key), CHINESE_TIPS.get(sheet.name, {}).get(key, ""))


def parse_table(workbook: Path, sheet: xlrd.sheet.Sheet) -> TableDefinition | None:
    """Parse a worksheet, returning None when it has no cells."""

    if sheet.nrows == 0 or sheet.ncols == 0:
        return None

    key_row = get_metadata_row(sheet, "KEY")
    type_row = get_metadata_row(sheet, "TYPE")
    client_enabled_row = get_metadata_row_by_labels(sheet, CLIENT_ENABLED_LABELS, "IS_CLIENT")
    server_enabled_row = get_metadata_row_by_labels(sheet, SERVER_ENABLED_LABELS, "IS_SERVER")
    client_class_name = parse_class_name(
        get_first_value(sheet, CLIENT_OUTPUT_LABELS), "client", sheet
    )
    server_class_name = parse_class_name(
        get_first_value(sheet, SERVER_OUTPUT_LABELS), "server", sheet
    )
    client_fields = parse_fields(sheet, key_row, type_row, client_enabled_row)
    server_fields = parse_fields(sheet, key_row, type_row, server_enabled_row)
    values = [
        sheet.row_values(row_index)
        for row_index in range(type_row + 1, sheet.nrows)
        if normalize_label(sheet.cell_value(row_index, 0)) == "VALUE"
    ]
    if client_class_name is not None:
        validate_table_ids(sheet, values, client_fields, "client")
    if server_class_name is not None:
        validate_table_ids(sheet, values, server_fields, "server")
    if client_class_name is not None:
        validate_enum_types(sheet, values, client_fields, "client")
    if server_class_name is not None:
        validate_enum_types(sheet, values, server_fields, "server")

    return TableDefinition(
        workbook=workbook,
        sheet_name=sheet.name,
        table_id_name=parse_table_id_name(sheet),
        client_class_name=client_class_name,
        server_class_name=server_class_name,
        client_fields=client_fields,
        server_fields=server_fields,
        values=values,
    )


def get_metadata_row_by_labels(
    sheet: xlrd.sheet.Sheet, labels: set[str], display_name: str
) -> int:
    """Return a metadata row matched by any supported spelling."""

    for row_index in range(sheet.nrows):
        if normalize_label(sheet.cell_value(row_index, 0)) in labels:
            return row_index
    raise ValueError(f"{sheet.name} 缺少 {display_name} 行。")


def validate_table_ids(
    sheet: xlrd.sheet.Sheet,
    values: list[list[Any]],
    fields: list[FieldDefinition],
    side: str,
) -> None:
    """Require each generated endpoint table to use stable sequential positive Id values."""

    id_field = next((field for field in fields if field.name.lower() == "id"), None)
    if id_field is None:
        raise ValueError(f"{sheet.name} 的 {side} 表必须启用 KEY 为 Id 的字段。")
    if id_field.type_name != "int":
        raise ValueError(f"{sheet.name} 的 {side} 表 Id 字段类型必须为 int。")
    if not values:
        raise ValueError(f"{sheet.name} 的 {side} 表至少需要一条 VALUE 数据。")

    ids: list[int] = []
    for row_offset, row in enumerate(values, start=1):
        value = row[id_field.column_index] if id_field.column_index < len(row) else None
        context = f"{sheet.name} VALUE 第 {row_offset} 行的 Id"
        if is_empty(value):
            raise ValueError(f"{context} 不能为空。")
        try:
            number = Decimal(str(value))
        except (InvalidOperation, ValueError) as error:
            raise ValueError(f"{context} 必须为 int。") from error
        if number != number.to_integral_value() or number <= 0:
            raise ValueError(f"{context} 必须为正整数。")
        ids.append(int(number))

    if ids[0] != 1:
        raise ValueError(f"{sheet.name} 的 {side} 表首条 VALUE 数据 Id 必须为 1。")
    if len(set(ids)) != len(ids):
        raise ValueError(f"{sheet.name} 的 {side} 表 Id 不能重复。")


def validate_enum_types(
    sheet: xlrd.sheet.Sheet,
    values: list[list[Any]],
    fields: list[FieldDefinition],
    side: str,
) -> None:
    """Validate optional EnumType names before generating a row-id enum."""
    enum_field = next((field for field in fields if field.name == "EnumType"), None)
    if enum_field is None:
        return
    if enum_field.type_name != "string":
        raise ValueError(f"{sheet.name} 的 {side} 表 EnumType 字段类型必须为 string。")
    names: set[str] = set()
    enum_name = f"{sheet.name}Id"
    for row_offset, row in enumerate(values, start=1):
        value = row[enum_field.column_index] if enum_field.column_index < len(row) else None
        name = str(value).strip() if not is_empty(value) else ""
        if not name:
            raise ValueError(f"{sheet.name} 的 {side} 表 VALUE 第 {row_offset} 行 EnumType 不能为空。")
        if not IDENTIFIER_PATTERN.fullmatch(name) or name in CSHARP_KEYWORDS or name == enum_name:
            raise ValueError(f"{sheet.name} 的 {side} 表 EnumType {name!r} 不是合法 C# 枚举成员名。")
        if name in names:
            raise ValueError(f"{sheet.name} 的 {side} 表 EnumType {name!r} 重复。")
        names.add(name)


def default_literal(type_name: str) -> str:
    """Return the C# literal used when an optional configuration cell is empty."""

    if type_name == "string":
        return "string.Empty"
    if type_name.endswith("[]"):
        return "[]"
    return "default"


def render_scalar_literal(value: Any, type_name: str, context: str) -> str:
    """Convert one non-empty scalar Excel value into a valid C# literal."""

    if type_name == "SceId":
        if not isinstance(value, str):
            raise ValueError(f"{context} 的 SceId 必须为数编字符串标识，不能填写数值。")
        return f"new SceId({json.dumps(value, ensure_ascii=False)})"
    if type_name == "string":
        return json.dumps(str(value), ensure_ascii=False)
    if type_name == "char":
        text = str(value)
        if len(text) != 1:
            raise ValueError(f"{context} 的 char 值必须恰好包含一个字符。")
        escaped = {
            "\\": "\\\\",
            "'": "\\'",
            "\n": "\\n",
            "\r": "\\r",
            "\t": "\\t",
            "\0": "\\0",
        }.get(text, text)
        return f"'{escaped}'"
    if type_name == "bool":
        if isinstance(value, bool):
            return str(value).lower()
        normalized = str(value).strip().lower()
        if normalized in {"true", "1", "yes", "y"}:
            return "true"
        if normalized in {"false", "0", "no", "n"}:
            return "false"
        raise ValueError(f"{context} 的 bool 值 {value!r} 无法解析。")
    if type_name in {"float", "double", "decimal"}:
        try:
            number = Decimal(str(value))
        except (InvalidOperation, ValueError) as error:
            raise ValueError(f"{context} 的 {type_name} 值 {value!r} 无法解析。") from error
        if not number.is_finite():
            raise ValueError(f"{context} 的 {type_name} 值必须为有限数。")
        literal = format(number.normalize(), "f")
        return f"{literal}{'f' if type_name == 'float' else 'm' if type_name == 'decimal' else 'd'}"

    integer_ranges = {
        "sbyte": (-128, 127, ""),
        "byte": (0, 255, ""),
        "short": (-32768, 32767, ""),
        "ushort": (0, 65535, ""),
        "int": (-2147483648, 2147483647, ""),
        "uint": (0, 4294967295, "u"),
        "long": (-9223372036854775808, 9223372036854775807, "L"),
        "ulong": (0, 18446744073709551615, "UL"),
    }
    lower, upper, suffix = integer_ranges[type_name]
    try:
        number = Decimal(str(value))
    except (InvalidOperation, ValueError) as error:
        raise ValueError(f"{context} 的 {type_name} 值 {value!r} 无法解析。") from error
    if number != number.to_integral_value() or not lower <= number <= upper:
        raise ValueError(f"{context} 的 {type_name} 值 {value!r} 超出有效范围。")
    return f"{int(number)}{suffix}"


def render_literal(value: Any, type_name: str, context: str) -> str:
    """Convert an Excel cell, including JSON arrays, into a C# initializer."""

    if is_empty(value):
        return default_literal(type_name)
    if not type_name.endswith("[]"):
        return render_scalar_literal(value, type_name, context)
    if not isinstance(value, str):
        raise ValueError(f"{context} 的数组值必须是 JSON 数组文本。")
    try:
        items = json.loads(value)
    except json.JSONDecodeError as error:
        raise ValueError(f"{context} 的数组 JSON 无效：{error.msg}。") from error
    if not isinstance(items, list):
        raise ValueError(f"{context} 的数组值必须是 JSON 数组。")
    scalar_type = type_name[:-2]
    return "[" + ", ".join(
        render_scalar_literal(item, scalar_type, context) for item in items
    ) + "]"


def render_struct(
    class_name: str, fields: list[FieldDefinition], values: list[list[Any]], sheet_name: str
) -> list[str]:
    """Render one endpoint's struct and its static configuration list."""

    lines = [
        f"/// <summary>{sheet_name} 配置表的自动生成项。</summary>",
        f"public struct {class_name}",
        "{",
    ]
    for field in fields:
        # 将策划提示同步到公开字段契约；转义 XML，防止比较符号破坏生成注释。
        if field.tips:
            tip = html.escape(" ".join(field.tips.splitlines()), quote=False)
            lines.append(f"    /// <summary>{tip}</summary>")
        lines.append(f"    public {field.type_name} {field.name};")
    if {"ZhCn", "EnUs"}.issubset({field.name for field in fields}):
        language_fields = [field for field in fields if field.name not in {"Id", "Code", "EnumType"}]
        if any(field.type_name != "string" for field in language_fields):
            raise ValueError("Lang 的语言列必须为 string。")
        lines.extend([
            "",
            "    /// <summary>按语言列名读取当前行的翻译；未知语言返回空。</summary>",
            "    /// <param name=\"language\">Excel KEY 行中的语言列名。</param>",
            "    /// <returns>对应语言文本；列不存在时为空。</returns>",
            "    public readonly string? GetLanguage(string language) => language switch",
            "    {",
        ])
        lines.extend(f'        "{field.name}" => {field.name},' for field in language_fields)
        lines.extend(["        _ => null,", "    };", ""])
    lines.extend([
        "",
        "    /// <summary>配置表中的全部有效数据。</summary>",
        f"    public static readonly List<{class_name}> List = new()",
        "    {",
    ])
    for row_offset, row in enumerate(values, start=1):
        lines.append(f"        new {class_name}")
        lines.append("        {")
        for field in fields:
            value = row[field.column_index] if field.column_index < len(row) else None
            # 属性未填写边界时采用运行时一致的缺省值；显式填写的 0 必须保留。
            if sheet_name == "Attribute" and is_empty(value):
                if field.name == "MaxValue":
                    value = 2147483647
                elif field.name == "MinValue":
                    value = 0
            context = f"{sheet_name} VALUE 第 {row_offset} 行、第 {field.column_index + 1} 列"
            lines.append(f"            {field.name} = {render_literal(value, field.type_name, context)},")
        lines.append("        },")
    lines.extend(["    };", "}", ""])
    return lines


def render_file(tables: list[TableDefinition], side: str) -> str:
    """Render every eligible worksheet from one workbook into a side-specific file."""

    condition = "CLIENT" if side == "client" else "SERVER"
    lines = [
        GENERATED_MARKER,
        "// 由 mytool/generate_config_tables.py 从 common/xlsl 生成。请修改 Excel 源表，不要直接编辑此文件。",
        f"#if {condition}",
        "using System.Collections.Generic;",
        "",
        "namespace GameEntry.Config;",
        "",
    ]
    if any({"ZhCn", "EnUs"}.issubset({field.name for field in
           (table.client_fields if side == "client" else table.server_fields)}) for table in tables):
        lines.insert(3, "#nullable enable")
    for table in tables:
        class_name = table.client_class_name if side == "client" else table.server_class_name
        fields = table.client_fields if side == "client" else table.server_fields
        if class_name is not None:
            if any(field.name == "EnumType" for field in fields):
                lines.extend(render_row_enum(table, fields))
            lines.extend(render_struct(class_name, fields, table.values, table.sheet_name))
    lines.append("#endif")
    return "\n".join(lines)


def render_row_enum(table: TableDefinition, fields: list[FieldDefinition]) -> list[str]:
    """Render stable enum members from EnumType names and row Id values."""
    id_field = next(field for field in fields if field.name == "Id")
    enum_field = next(field for field in fields if field.name == "EnumType")
    lines = [
        f"/// <summary>{table.sheet_name} 配置行的稳定 Id。</summary>",
        f"public enum {table.sheet_name}Id : int",
        "{",
    ]
    for row in table.values:
        name = str(row[enum_field.column_index]).strip()
        identifier = int(Decimal(str(row[id_field.column_index])))
        lines.extend((
            f"    /// <summary>{name}，对应配置 Id {identifier}。</summary>",
            f"    {name} = {identifier},",
        ))
    lines.extend(("}", ""))
    return lines


def render_registry(tables: list[TableDefinition], side: str) -> str:
    """Render the endpoint table enum and registration bridge for ConfigSystem."""

    condition = "CLIENT" if side == "client" else "SERVER"
    endpoint_tables = [
        table
        for table in tables
        if (table.client_class_name if side == "client" else table.server_class_name) is not None
    ]
    lines = [
        GENERATED_MARKER,
        "// 由 mytool/generate_config_tables.py 从 common/xlsl 生成。请修改 Excel 源表，不要直接编辑此文件。",
        f"#if {condition}",
        "",
        "namespace GameEntry.Config;",
        "",
        "/// <summary>当前端可用配置表的唯一标识。</summary>",
        "public enum ConfigTableId",
        "{",
        "    /// <summary>无效配置表标识。</summary>",
        "    None = 0,",
    ]
    for index, table in enumerate(endpoint_tables, start=1):
        lines.extend([
            f"    /// <summary>{table.sheet_name} 配置表。</summary>",
            f"    {table.table_id_name} = {index},",
        ])
    lines.extend([
        "}",
        "",
        "/// <summary>将导出的静态配置表登记到当前端 ConfigSystem。</summary>",
        "internal static class ConfigTableRegistry",
        "{",
        "    /// <summary>登记当前端全部自动生成的配置表。</summary>",
        "    /// <param name=\"configSystem\">要初始化的非空配置系统。</param>",
        "    /// <exception cref=\"ArgumentNullException\">配置系统为空时引发。</exception>",
        "    internal static void RegisterAll(ConfigSystem configSystem)",
        "    {",
        "        ArgumentNullException.ThrowIfNull(configSystem);",
    ])
    for table in endpoint_tables:
        class_name = table.client_class_name if side == "client" else table.server_class_name
        fields = table.client_fields if side == "client" else table.server_fields
        field_names = {field.name for field in fields}
        code_selector = "static record => record.Code" if "Code" in field_names else "null"
        lines.append(
            f"        configSystem.RegisterGeneratedTable(ConfigTableId.{table.table_id_name}, {class_name}.List, static record => record.Id, {code_selector});"
        )
    lines.extend(["    }", "}", "#endif", ""])
    return "\n".join(lines)


def collect_workbooks(source_directory: Path) -> list[Path]:
    """Discover all legacy Excel configuration workbooks in deterministic order."""

    return sorted(path for path in source_directory.rglob("*.xls") if path.is_file())


def build_tables(workbook: Path) -> list[TableDefinition]:
    """Parse all non-empty worksheets in one workbook."""

    book = xlrd.open_workbook(workbook)
    return [
        table
        for sheet in book.sheets()
        if (table := parse_table(workbook, sheet)) is not None
    ]


def validate_unique_class_names(tables: list[TableDefinition], side: str) -> None:
    """Reject duplicate class names emitted by different worksheets."""

    class_names = [
        table.client_class_name if side == "client" else table.server_class_name
        for table in tables
        if (table.client_class_name if side == "client" else table.server_class_name) is not None
    ]
    duplicate_names = {
        class_name for class_name in class_names if class_names.count(class_name) > 1
    }
    if duplicate_names:
        raise ValueError(f"{side} 配置类名重复：{', '.join(sorted(duplicate_names))}。")


def validate_unique_table_ids(tables: list[TableDefinition], side: str) -> None:
    """Reject duplicate enum members caused by repeated worksheet names."""

    endpoint_tables = [
        table
        for table in tables
        if (table.client_class_name if side == "client" else table.server_class_name) is not None
    ]
    table_ids = [table.table_id_name for table in endpoint_tables]
    duplicate_ids = {table_id for table_id in table_ids if table_ids.count(table_id) > 1}
    if duplicate_ids:
        raise ValueError(f"{side} 配置表枚举名称重复：{', '.join(sorted(duplicate_ids))}。")


def write_or_check(path: Path, content: str, check: bool) -> None:
    """Write one generated file or require it to be exactly current."""

    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise ValueError(f"{display_path(path)} 与生成结果不一致。")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def remove_stale_files(output_directory: Path, expected: set[str], check: bool) -> None:
    """Remove only generator-owned files for workbooks that no longer exist."""

    if not output_directory.exists():
        return
    # Windows写入同名异大小写路径会保留旧文件名；清理不能把刚生成的有效文件删掉。
    expected_names = {name.casefold() for name in expected} if sys.platform == "win32" else expected
    for path in output_directory.glob("*.cs"):
        actual_name = path.name.casefold() if sys.platform == "win32" else path.name
        if actual_name in expected_names:
            continue
        if not path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            continue
        if check:
            raise ValueError(f"{display_path(path)} 是陈旧的配置生成文件。")
        path.unlink()


def display_path(path: Path) -> Path:
    """Prefer a repository-relative path while supporting isolated test folders."""

    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def main() -> int:
    """Export all workbooks, or check whether checked-in generated files are current."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="仅校验生成文件是否最新。")
    parser.add_argument("--source", type=Path, default=SOURCE_DIRECTORY, help="Excel 源目录。")
    parser.add_argument("--client-output", type=Path, default=CLIENT_OUTPUT_DIRECTORY)
    parser.add_argument("--server-output", type=Path, default=SERVER_OUTPUT_DIRECTORY)
    arguments = parser.parse_args()

    if not arguments.source.exists():
        raise ValueError(f"Excel 源目录不存在：{arguments.source}")
    all_tables: list[TableDefinition] = []
    workbooks: list[tuple[Path, list[TableDefinition]]] = []
    for workbook in collect_workbooks(arguments.source):
        tables = build_tables(workbook)
        all_tables.extend(tables)
        workbooks.append((workbook, tables))
    validate_unique_class_names(all_tables, "client")
    validate_unique_class_names(all_tables, "server")
    validate_unique_table_ids(all_tables, "client")
    validate_unique_table_ids(all_tables, "server")

    # 公式必须在写任何文件之前完成跨表、字段、端侧和依赖校验，避免留下半套配置。
    from calculation_compiler import generate_calculations
    calculation_outputs = {side: generate_calculations(all_tables, side) for side in ("client", "server")}
    from buff_config_validator import validate_buffs
    for side in ("client", "server"): validate_buffs(all_tables, side)

    client_expected: set[str] = {"ConfigTableRegistry.g.cs"}
    server_expected: set[str] = {"ConfigTableRegistry.g.cs"}
    for workbook, tables in workbooks:
        output_name = f"{workbook.stem}.cs"
        client_tables = [table for table in tables if table.client_class_name is not None]
        server_tables = [table for table in tables if table.server_class_name is not None]
        if client_tables:
            if output_name in client_expected:
                raise ValueError(f"客户端输出文件名重复：{output_name}。")
            client_expected.add(output_name)
            write_or_check(arguments.client_output / output_name, render_file(client_tables, "client"), arguments.check)
        if server_tables:
            if output_name in server_expected:
                raise ValueError(f"服务器输出文件名重复：{output_name}。")
            server_expected.add(output_name)
            write_or_check(arguments.server_output / output_name, render_file(server_tables, "server"), arguments.check)
    write_or_check(
        arguments.client_output / "ConfigTableRegistry.g.cs",
        render_registry(all_tables, "client"),
        arguments.check)
    write_or_check(
        arguments.server_output / "ConfigTableRegistry.g.cs",
        render_registry(all_tables, "server"),
        arguments.check)
    remove_stale_files(arguments.client_output, client_expected, arguments.check)
    remove_stale_files(arguments.server_output, server_expected, arguments.check)
    for side, config_output in (("client", arguments.client_output), ("server", arguments.server_output)):
        calculation_output = config_output.parent.parent / "Calculation" / config_output.name
        expected = set(calculation_outputs[side])
        for name, content in calculation_outputs[side].items():
            write_or_check(calculation_output / name, content, arguments.check)
        if calculation_output.exists():
            remove_stale_files(calculation_output, expected, arguments.check)
    return 0


if __name__ == "__main__" and not globals().get("COMPAT_IMPORT", False):
    try:
        raise SystemExit(main())
    except (OSError, ValueError, xlrd.XLRDError) as error:
        print(error, file=sys.stderr)
        raise SystemExit(1)
